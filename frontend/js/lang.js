function t(key) {
    return translations[currentLang]?.[key] ?? translations.ru[key] ?? key;
}

function toggleLang() {
    currentLang = currentLang === 'ru' ? 'en' : 'ru';
    localStorage.setItem('language', currentLang);
    window.currentLang = currentLang;
    updateUILanguage();
    updateLanguageButton();
}

function updateLanguageButton() {
    const el = document.querySelector('.lang-text');
    if (el) el.textContent = currentLang === 'ru' ? 'Русский' : 'English';
}

function updateCustomSelect(hiddenInputId, map) {
    const select = document.querySelector(`#${hiddenInputId}`)?.previousElementSibling;
    if (!select?.classList.contains('custom-select')) return;
    select.querySelectorAll('.custom-select-option').forEach(option => {
        const translated = map[option.dataset.value];
        if (!translated) return;
        option.textContent = translated;
        if (option.classList.contains('selected')) {
            const label = select.querySelector('.custom-select-label');
            if (label) label.textContent = translated;
        }
    });
}

function updateSelectOptions() {
    updateCustomSelect('style', {
        synonyms: t('style_synonyms'), simple: t('style_simple'), formal: t('style_formal'),
        creative: t('style_creative'), professional: t('style_professional'),
        human: t('style_human'), literary: t('style_literary'), academic: t('style_academic')
    });
}

function setTranslatedText(element, value) {
    const icon = element.querySelector(':scope > i');
    if (!icon) {
        element.textContent = value;
        return;
    }

    element.replaceChildren(icon, document.createTextNode(` ${value}`));
}

function updateUILanguage() {
    document.documentElement.lang = currentLang;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        setTranslatedText(el, t(key));
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        el.placeholder = t(el.getAttribute('data-i18n-placeholder'));
    });

    document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
        el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria-label')));
    });

    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = t(el.getAttribute('data-i18n-title'));
    });

    document.querySelectorAll('[data-i18n-document-title]').forEach(el => {
        document.title = `Humary — ${t(el.getAttribute('data-i18n-document-title'))}`;
    });

    document.querySelectorAll('[data-i18n-words-counter]').forEach(el => {
        el.textContent = el.textContent.replace(/\b(?:слов|words)\b/iu, t('words'));
    });

    const subscriptionText = document.getElementById('subscribeTypeText');
    if (subscriptionText) {
        const planType = window.currentSubscription?.plan_type || 'free';
        subscriptionText.textContent = t(`subscription_${planType}`);
    }

    updateSelectOptions();

    const authBtn = document.getElementById('authBtn');
    if (authBtn && typeof Auth !== 'undefined') {
        const authText = authBtn.querySelector('span');
        if (authText) authText.textContent = Auth.isAuthenticated() ? t('logout') : t('login');
    }

    // The passwordless auth screen is fully translated through its data-i18n
    // attributes above; it has no login/registration mode switch.
}

function initLanguage() {
    updateLanguageButton();
    updateUILanguage();
}

window.t = t;
window.currentLang = currentLang;
window.toggleLang = toggleLang;
window.switchLanguage = toggleLang;
window.initLanguage = initLanguage;

if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initLanguage, { once: true });
} else {
    initLanguage();
}
