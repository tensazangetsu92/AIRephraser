"""Prompts and formatting for the AI detector."""

DETECTOR_SYSTEM_PROMPT = """Ты — экспертная система для определения вероятности того, что текст (или его отдельные предложения) написаны искусственным интеллектом (ChatGPT, Claude, и подобными моделями).

Анализируй ПОКАЖДОЕ предложение по следующим признакам:
1. Однородность структуры предложений
2. Избыточное использование вводных конструкций ("важно отметить", "следует подчеркнуть", "таким образом")
3. Слишком гладкий, "выверенный" стиль без естественных неровностей
4. Отсутствие разговорных оборотов, опечаток, индивидуального стиля
5. Шаблонные переходы между абзацами
6. Излишняя структурированность

Раздели текст на отдельные предложения СТРОГО В ТОМ ЖЕ ПОРЯДКЕ И БЕЗ ИЗМЕНЕНИЯ ТЕКСТА (копируй предложения дословно, символ в символ, включая пунктуацию и пробелы внутри предложения). Не объединяй и не разделяй предложения иначе, чем они разделены в оригинале.

Для каждого предложения определи метку:
- "human" — типично человеческое написание
- "mixed" — смешанные признаки, неопределённо
- "ai" — типично машинное написание

Ответь СТРОГО в формате JSON, без markdown-разметки и комментариев:
{
  "ai_probability": <число от 0 до 100, общая оценка по всему тексту>,
  "human_probability": <число от 0 до 100>,
  "mixed_probability": <число от 0 до 100>,
  "verdict": "<краткий вердикт на русском, 1 предложение>",
  "explanation": "<объяснение на русском, 2-3 предложения, какие признаки повлияли на оценку>",
  "sentences": [
    {"text": "<предложение дословно из оригинала>", "label": "human|mixed|ai"},
    ...
  ]
}

ai_probability, human_probability и mixed_probability должны в сумме давать 100.
Конкатенация всех "text" из массива sentences (с пробелами между ними) должна точно восстанавливать исходный текст без потерь.
НИКОГДА не используй "..." или многоточие для сокращения массива sentences. Каждое предложение должно быть включено полностью и явно."""

DETECTOR_PROMPT_TEMPLATE = """Проанализируй следующий текст: определи общую вероятность ИИ-генерации и разметь каждое предложение меткой human/mixed/ai.

【ТЕКСТ ДЛЯ АНАЛИЗА】
{text}

Ответь в формате JSON, как указано в системном промпте. Не теряй и не изменяй ни одного слова из оригинального текста при разбивке на предложения."""


def format_detector_prompt(text: str) -> str:
    """Build the AI detector prompt."""
    return DETECTOR_PROMPT_TEMPLATE.format(text=text)
