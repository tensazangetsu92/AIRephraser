"""Prompts and formatting for the AI detector."""

import json


DETECTOR_LABEL_SYSTEM_PROMPT = """Ты оцениваешь, насколько фрагменты текста похожи на текст, созданный ИИ.
В нём могут встречаться чуть более простые или неидеально отполированные, но понятные формулировки; сами по себе они не являются признаком низкого качества или ИИ-генерации, если мысль и структура текста развиваются последовательно.
Отсутствие шаблонных вводных фраз вроде «Следует отметить» — скорее признак естественного текста.
Предложения разной длины говорят о том, что текст человеческий.
Предложения с четкой личной позицией (ОСОБЕННО С МЕСТОИМЕНИЕМ "я") говорят о том, что текст человеческий.
Есть формулировки по типу: "Каждый день мы сталкиваемся с экономикой" кажется что слова тут подобраны не очень корректно, правильней было бы сказать "сталкиваемся с понятием экономики" или что то типо того, но это небольшая простота в тексте и отдельных фразах и делает человеческим

Каждый фрагмент уже выделен сервером. Не объединяй, не разделяй, не переписывай и не цитируй их.
Для каждого фрагмента выбери ровно одну метку: human, mixed или ai.
Не определяй метку по одной только академической или официальной манере письма. Термины, списки, ссылки, цитаты, длинные предложения, последовательная структура и нейтральный тон сами по себе не означают, что текст создан ИИ.
Ставь ai только при нескольких независимых сильных признаках шаблонной генерации внутри конкретного фрагмента. Если данных недостаточно или признаки неоднозначны, ставь mixed. Не назначай одинаковую метку всем фрагментам автоматически только из-за общего стиля или темы текста.
Верни только JSON-массив без Markdown и пояснительного текста:
["human", "mixed", "ai"].
Количество меток должно совпадать с количеством входных фрагментов. Порядок меток должен точно соответствовать порядку фрагментов во входном массиве."""


DETECTOR_LABEL_PROMPT_TEMPLATE = """Оцени каждый подготовленный фрагмент.
Учитывай однотипность структуры, шаблонные вводные фразы, чрезмерную гладкость текста, шаблонные переходы и излишнюю структурированность.
Не меняй текст фрагментов и не возвращай их в ответе: верни только id и label.

Входные фрагменты JSON:
{payload}"""


def format_detector_label_prompt(items: list[dict]) -> str:
    """Build a label-only prompt for server-segmented detector fragments."""
    return DETECTOR_LABEL_PROMPT_TEMPLATE.format(
        payload=json.dumps([{"text": item["text"]} for item in items], ensure_ascii=False),
    )
