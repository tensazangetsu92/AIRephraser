"""Quality-review prompts for generated Humanize text."""

from prompt_templates.humanizer import split_humanize_paragraphs

HUMANIZE_REVIEW_SYSTEM_PROMPT = """Ты — корректор качества после рерайта. Сравни исходный и переработанный текст.
Проверь каждое предложение переработанного текста на явные ошибки в сочетаемости слов, которые делают фразу неестественной, внутренне противоречивой или искажают смысл исходника. 
Проверь предложения на смысловую несогласованность
Замени слишком сложные термины на более простые слова
Отмечай неудачную замену естественного устойчивого сочетания, даже если она формально грамматически верна.

Исправь только такие ошибки минимальными заменами. Не переписывай текст заново, 
не улучшай стиль ради красоты и не меняй допустимые варианты перефразирования.
Сохрани все остальные слова, структуру, абзацы, заголовки, списки, факты и смысл без изменений.
Если ошибок нет, верни текст без изменений.
Верни только готовый текст без комментариев, JSON и Markdown."""


def format_humanize_review_prompt(source_text: str, rewritten_text: str) -> str:
    """Build the one-pass semantic review and correction request."""
    paragraph_count = len(split_humanize_paragraphs(source_text))
    return f"""Проверь результат рерайта по исходнику.

В исходнике {paragraph_count} абзацев. Верни ровно {paragraph_count} абзацев: не объединяй их, не удаляй и не дроби.

Пример ошибки, которую обязательно исправляй:
Исходник: «в человеческом обществе она всё больше опирается на авторитет, знания и экономические рычаги».
Неверный рерайт: в человеческих сообществах
«человеческие сообщества» здесь неестественно заменяет устойчивое сочетание «человеческое общество»
Исправление: «в человеческом обществе».

<source>
{source_text}
</source>

<rewritten_text>
{rewritten_text}
</rewritten_text>"""
