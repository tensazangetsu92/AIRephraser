"""Prompts and formatting for the Paraphraser tool."""


PARAPHRASER_COMMON_SYSTEM_PROMPT = """Ты выполняешь точечное перефразирование слов в тексте.
Сохраняй полный смысл, все идеи, факты и степень уверенности автора.
Не меняй структуру предложений, порядок слов, падежа слов, синтаксические и грамматические связи, пунктуацию, границы предложений, абзацев, заголовков и списков.
Меняй только отдельные сложные, тяжёлые или канцелярские слова и устойчивые словосочетания на точные синонимы.
Не изменяй цифры, даты, имена, названия, ссылки, цитаты, термины, формулы и обозначения. Не добавляй и не удаляй информацию, примеры, оценки, выводы или детали.
Сохраняй исходные табуляции, пробелы перед абзацами и пустые строки между абзацами.
Если слово, термин или формулировка уже понятны и нужны для смысла, не меняй их.
Ответ возвращай только готовым текстом без комментариев и пояснений."""


PARAPHRASER_STYLE_SYSTEM_PROMPTS = {
    "synonyms": """Ты работаешь в режиме «Синонимы».
Сохрани исходную манеру текста. Выбирай нейтральные точные синонимы и меняй только слова или выражения, которые действительно сложны, тяжеловесны или канцелярски звучат.
Не заменяй слова ради самого факта замены.""",
    "simple": """Ты работаешь в режиме «Простой».
Если есть несколько точных вариантов, выбирай самый понятный и распространённый синоним. Упрощай только отдельные трудные слова и выражения.
Не упрощай специальные термины, без которых теряется смысл, и не делай текст разговорным.""",
    "academic": """Ты работаешь в режиме «Академический».
Сохрани учебно-научную манеру и терминологическую точность. Заменяй только излишне сложные или неясные слова и выражения на ясные академические синонимы.
Не добавляй канцелярит, не меняй специальные термины и не делай текст разговорным.""",
}


def get_paraphraser_system_prompt(style: str) -> str:
    """Build the system prompt for the selected Paraphraser editing mode."""
    style_prompt = PARAPHRASER_STYLE_SYSTEM_PROMPTS.get(
        style,
        PARAPHRASER_STYLE_SYSTEM_PROMPTS["synonyms"],
    )
    return f"{PARAPHRASER_COMMON_SYSTEM_PROMPT}\n\n{style_prompt}"


# Backward-compatible export. Live Paraphraser requests use get_paraphraser_system_prompt().
PARAPHRASER_SYSTEM_PROMPT = PARAPHRASER_COMMON_SYSTEM_PROMPT


PARAPHRASER_PROMPT_TEMPLATE = """Выполни точечную замену слов и устойчивых словосочетаний в исходном тексте.
Не переписывай предложения целиком и не используй Markdown-разметку.

【ИСХОДНЫЙ ТЕКСТ】
{text}
【КОНЕЦ ИСХОДНОГО ТЕКСТА】

Выведи только готовый текст."""


def format_paraphraser_prompt(text: str, style: str) -> str:
    """Build the user prompt for the Paraphraser tool."""
    # The style is intentionally selected in the system prompt, not appended here.
    return PARAPHRASER_PROMPT_TEMPLATE.format(text=text)
