"""Prompts and formatting for the Paraphraser tool."""

PARAPHRASER_SYSTEM_PROMPT = """Ты — профессиональный редактор и лингвист. Твоя задача — перефразировать текст, сохранив его смысл, но изменив формулировки, структуру предложений и порядок слов.

ПРАВИЛА:
1. СОХРАНИ полный смысл и все ключевые идеи оригинала
2. ЗАМЕНИ формулировки на синонимичные, избегая дословного копирования
3. МОЖЕШЬ менять структуру предложений (объединять, разбивать, менять порядок частей)
4. СОХРАНИ общую длину текста (±20%)
5. СОХРАНИ все цифры, даты, имена, термины и названия без изменений
6. НЕ добавляй новую информацию, которой нет в оригинале
7. НЕ удаляй важные детали и аргументы

ОТВЕТАЙ ТОЛЬКО ГОТОВЫМ ПЕРЕФРАЗИРОВАННЫМ ТЕКСТОМ, БЕЗ КОММЕНТАРИЕВ И ПОЯСНЕНИЙ."""

PARAPHRASER_PROMPT_TEMPLATE = """Перефразируй следующий текст. Стиль: {style}. Тон: {tone}.

【ИСХОДНЫЙ ТЕКСТ】
{text}

Перефразируй так, чтобы текст звучал по-другому, но сохранял тот же смысл. Все цифры, имена и термины оставь без изменений. Ответь ТОЛЬКО готовым текстом."""

PARAPHRASER_STYLE_MAP = {
    "similar": "максимально близкий к оригинальному стилю, только другие слова",
    "formal": "формальный, официально-деловой стиль",
    "simple": "простой и понятный язык, без сложных конструкций",
    "creative": "живой, образный язык с нестандартными оборотами",
    "academic": "строго академический, научный стиль",
}

PARAPHRASER_TONE_MAP = {
    "neutral": "нейтральный",
    "formal": "формальный",
    "casual": "разговорный",
    "friendly": "дружелюбный",
    "academic": "академический",
}


def format_paraphraser_prompt(text: str, style: str, tone: str) -> str:
    """Build the Paraphraser prompt."""
    return PARAPHRASER_PROMPT_TEMPLATE.format(
        text=text,
        style=PARAPHRASER_STYLE_MAP.get(style, PARAPHRASER_STYLE_MAP["similar"]),
        tone=PARAPHRASER_TONE_MAP.get(tone, PARAPHRASER_TONE_MAP["neutral"]),
    )
